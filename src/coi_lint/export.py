"""Exports for renewal tracking: an iCalendar (.ics) file and renewal-request drafts."""

from __future__ import annotations

import json
from collections import defaultdict
from datetime import date, timedelta

from .renewals import WINDOWS, Renewal


def _esc(text: str) -> str:
    """Escape text for an iCalendar TEXT value (RFC 5545 §3.3.11)."""
    return text.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n")


def ics(renewals: list[Renewal], today: date) -> str:
    """One all-day event per policy on its expiry date, with reminders 90, 60 and 30 days before.

    Already-expired policies are left out (there is nothing left to remind about).
    UIDs are stable, so re-importing an updated file updates events instead of duplicating them.
    """
    stamp = today.strftime("%Y%m%dT000000Z")
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//coi-lint//renewals//EN", "CALSCALE:GREGORIAN",
             "X-WR-CALNAME:COI renewals"]
    for r in renewals:
        if r.days_left < 0:
            continue
        uid = f"{r.policy_number or r.insured}-{r.coverage}-{r.expires.isoformat()}@coi-lint".replace(" ", "-")
        policy = r.policy_number or "(no number)"
        producer = r.producer or "the producer"
        summary = f"COI expires: {r.insured} — {r.label}"
        desc = f"Policy {policy} expires {r.expires.isoformat()}. Request a renewed certificate from {producer}."
        lines += [
            "BEGIN:VEVENT",
            f"UID:{_esc(uid)}",
            f"DTSTAMP:{stamp}",
            f"DTSTART;VALUE=DATE:{r.expires.strftime('%Y%m%d')}",
            f"DTEND;VALUE=DATE:{(r.expires + timedelta(days=1)).strftime('%Y%m%d')}",
            f"SUMMARY:{_esc(summary)}",
            f"DESCRIPTION:{_esc(desc)}",
        ]
        for w in sorted(WINDOWS, reverse=True):
            alarm = f"{w} days until {r.insured} {r.label} expires"
            lines += ["BEGIN:VALARM", "ACTION:DISPLAY", f"TRIGGER;RELATED=START:-P{w}D",
                      f"DESCRIPTION:{_esc(alarm)}", "END:VALARM"]
        lines.append("END:VEVENT")
    lines.append("END:VCALENDAR")
    return "\r\n".join(lines) + "\r\n"


def as_json(renewals: list[Renewal], today: date, within: int) -> str:
    return json.dumps({
        "today": today.isoformat(),
        "within_days": within,
        "renewals": [{
            "insured": r.insured, "producer": r.producer, "coverage": r.coverage,
            "policy_number": r.policy_number, "expires": r.expires.isoformat(),
            "days_left": r.days_left, "window": r.window, "source": r.source,
        } for r in renewals],
    }, indent=2)


def letters(renewals: list[Renewal]) -> str:
    """One renewal-request draft per producer. A human sends them, never the tool."""
    if not renewals:
        return "No renewals due in this window."
    by_producer: dict[str, list[Renewal]] = defaultdict(list)
    for r in renewals:
        by_producer[r.producer or "the producer listed on the certificate"].append(r)
    out = []
    for producer, items in by_producer.items():
        body = "\n".join(
            f"  - {r.insured}: {r.label}, policy {r.policy_number or '(no number)'}, "
            + (f"expired {r.expires.isoformat()}" if r.days_left < 0 else f"expires {r.expires.isoformat()}")
            for r in items
        )
        out.append(
            f"To: {producer}\nRe: Renewed certificates of insurance needed\n\n"
            f"Hello,\n\nThe following policies on certificates you issued to us are expiring or have expired:\n\n"
            f"{body}\n\nPlease send updated certificates once each policy is renewed.\n\nThank you.\n"
            f"(Draft generated by coi-lint; review before sending.)"
        )
    return ("\n\n" + "-" * 60 + "\n\n").join(out)
