"""Render findings as terminal text, JSON, or a plain-text deficiency letter; render renewal lists."""

from __future__ import annotations

import json
from dataclasses import asdict
from datetime import date

from .models import Certificate, Requirements
from .renewals import Renewal
from .rules import Finding, verdict

ICON = {"pass": "✓", "warn": "!", "fail": "✗", "waived": "~"}
COLOR = {"pass": "\033[32m", "warn": "\033[33m", "fail": "\033[31m", "waived": "\033[36m"}
DIM = "\033[2m"
RESET = "\033[0m"


def counts(findings: list[Finding]) -> dict[str, int]:
    return {k: sum(f.severity == k for f in findings) for k in ("fail", "warn", "waived", "pass")}


def text(cert: Certificate, req: Requirements, findings: list[Finding], color: bool = True, fixes: bool = True) -> str:
    def c(sev: str, s: str) -> str:
        return f"{COLOR[sev]}{s}{RESET}" if color else s

    def dim(s: str) -> str:
        return f"{DIM}{s}{RESET}" if color else s

    lines = [f"coi-lint · {cert.insured} → {req.name}", ""]
    for f in findings:
        lines.append(f"  {c(f.severity, ICON[f.severity])} {f.rule}  {f.message}")
        if fixes and f.fix and f.severity in ("fail", "warn"):
            lines.append(dim(f"           fix: {f.fix}"))
        if f.waiver:
            lines.append(dim(f"           waived: {f.waiver}"))
    n = counts(findings)
    sev = "fail" if n["fail"] else ("warn" if n["warn"] else "pass")
    waived = f", {n['waived']} waived" if n["waived"] else ""
    lines += ["", c(sev, f"{verdict(findings)}  ({n['fail']} fail, {n['warn']} warn{waived}, {n['pass']} pass)")]
    return "\n".join(lines)


def as_json(cert: Certificate, req: Requirements, findings: list[Finding]) -> str:
    return json.dumps({
        "insured": cert.insured,
        "requirements": req.name,
        "verdict": verdict(findings),
        "findings": [asdict(f) for f in findings],
    }, indent=2)


def letter(cert: Certificate, req: Requirements, findings: list[Finding]) -> str:
    """Draft a deficiency request to the insured's broker. A human sends it, never the tool."""
    issues = [f for f in findings if f.severity in ("fail", "warn")]
    if not issues:
        return f"No deficiencies found for {cert.insured} against {req.name}."
    body = "\n".join(f"  - {f.message} [{f.rule}]" + (f"\n    Requested: {f.fix}" if f.fix else "") for f in issues)
    return (
        f"To: {cert.producer or 'the producer listed on the certificate'}\n"
        f"Re: Certificate of insurance for {cert.insured} ({req.name})\n\n"
        f"Hello,\n\nWe reviewed the certificate issued {cert.issued.isoformat()} and need the following "
        f"corrected before work can continue:\n\n{body}\n\n"
        f"Please send a revised certificate naming {req.holder or 'us'} as certificate holder.\n\nThank you.\n"
        f"(Draft generated by coi-lint; review before sending.)"
    )


def renewals_text(items: list[Renewal], n_certs: int, today: date, within: int, color: bool = True) -> str:
    """Policies expiring soon, soonest first, grouped into expired / 30 / 60 / 90-day windows."""
    def c(sev: str, s: str) -> str:
        return f"{COLOR[sev]}{s}{RESET}" if color else s

    head = f"coi-lint renewals · {n_certs} certificate{'s' if n_certs != 1 else ''} · next {within} days (from {today.isoformat()})"
    if not items:
        return head + "\n\n  Nothing expires in this window."
    rows = []
    for r in items:
        if r.days_left < 0:
            sev, when = "fail", f"expired {-r.days_left}d ago"
        elif r.days_left <= 30:
            sev, when = "warn", f"{r.days_left}d left"
        else:
            sev, when = "pass", f"{r.days_left}d left"
        glyph = {"fail": "✗", "warn": "!", "pass": "·"}[sev]
        rows.append(f"  {c(sev, glyph)} {when:<18}{r.expires.isoformat()}  {r.insured} · {r.label} · {r.policy_number or '(no number)'}")
    expired = sum(r.days_left < 0 for r in items)
    soon = sum(0 <= r.days_left <= 30 for r in items)
    later = len(items) - expired - soon
    summary = f"{expired} expired, {soon} within 30 days, {later} within {within} days"
    sev = "fail" if expired else ("warn" if soon else "pass")
    return "\n".join([head, "", *rows, "", c(sev, summary)])

