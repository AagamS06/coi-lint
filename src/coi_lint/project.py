def to_html(s: dict) -> str:
    e = html.escape
    label = {"COMPLIANT": "✓ Compliant", "COMPLIANT_WITH_WARNINGS": "! Warnings", "DEFICIENT": "✗ Deficient"}
    cards = "".join(f'<div class="card"><b>{v}</b><span class="muted">{k}</span></div>' for k, v in [
        ("certificates", s["certificates"]), ("compliant", s["compliant"]), ("with warnings", s["warnings"]),
        ("deficient", s["deficient"]), ("renewals due", len(s["renewals"]))])
    rows = "".join(
        f"<tr><td>{e(i['insured'])}<div class='muted'>{e(i['producer'])}</div></td>"
        f"<td><span class='badge {i['verdict']}'>{label[i['verdict']]}</span></td>"
        f"<td>{'<br>'.join(e(p) for p in i['problems']) or '—'}</td></tr>" for i in s["insureds"])
    top = "".join(f"<li><code>{t['rule']}</code> {e(t['title'])}: {t['count']}×</li>" for t in s["top_failures"])
    ren = "".join(
        f"<tr><td>{r['expires']}</td><td>{e(r['insured'])}</td><td>{e(r['coverage'])}</td><td>{e(r['policy_number'])}</td>"
        f"<td>{r['days_left'] if r['days_left'] >= 0 else 'expired'}</td></tr>" for r in s["renewals"])
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>COI report — {e(s['project'])}</title>
<style>{_CSS}</style></head><body><main>
<h1>COI report — {e(s['project'])}</h1><div class="muted">Generated by coi-lint on {s['date']}</div>
<p class="lead">{e(headline(s))}</p><div class="cards">{cards}</div>
<h2>Certificates</h2><div class="table"><table><thead><tr><th>Insured</th><th>Verdict</th><th>Problems</th></tr></thead>
<tbody>{rows}</tbody></table></div>
{'<h2>Most common problems</h2><ul>' + top + '</ul>' if top else ''}
{'<h2>Renewals due</h2><div class="table"><table><thead><tr><th>Expires</th><th>Insured</th><th>Coverage</th><th>Policy</th><th>Days left</th></tr></thead><tbody>' + ren + '</tbody></table></div>' if ren else ''}
</main></body></html>
"""
