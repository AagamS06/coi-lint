"""Project report: the compliance picture across every certificate on a project.

Template-generated (no AI): a summary, a per-insured table, the most common problems, and
upcoming renewals. Rendered as Markdown (for PRs, wikis, Slack), a self-contained HTML page
(for GitHub Pages or email), or CSV (for Sheets/Excel registers).
"""

from __future__ import annotations

import csv
import html
import io
import json
from collections import Counter
from dataclasses import dataclass
from datetime import date

from .models import Certificate
from .renewals import Renewal
from .report import counts
from .rules import RULES, Finding, verdict


@dataclass
class Row:
    cert: Certificate
    findings: list[Finding]

    @property
    def verdict(self) -> str:
        return verdict(self.findings)

    @property
    def problems(self) -> list[Finding]:
        return [f for f in self.findings if f.severity in ("fail", "warn")]


def summary(rows: list[Row], renewals: list[Renewal], name: str, today: date) -> dict:
    by_verdict = Counter(r.verdict for r in rows)
    top = Counter(f.rule for r in rows for f in r.problems if f.severity == "fail").most_common(5)
    return {
        "project": name,
        "date": today.isoformat(),
        "certificates": len(rows),
        "compliant": by_verdict.get("COMPLIANT", 0),
        "warnings": by_verdict.get("COMPLIANT_WITH_WARNINGS", 0),
        "deficient": by_verdict.get("DEFICIENT", 0),
        "waived": sum(counts(r.findings)["waived"] for r in rows),
        "top_failures": [{"rule": k, "title": RULES.get(k, {}).get("title", k), "count": v} for k, v in top],
        "insureds": [{"insured": r.cert.insured, "producer": r.cert.producer, "verdict": r.verdict,
                      **{k: v for k, v in counts(r.findings).items()},
                      "problems": [f.message for f in r.problems], "source": r.cert.source} for r in rows],
        "renewals": [{"insured": x.insured, "coverage": x.label, "policy_number": x.policy_number,
                      "expires": x.expires.isoformat(), "days_left": x.days_left} for x in renewals],
    }


def headline(s: dict) -> str:
    """One sentence, written from the numbers. Used by every renderer and by the Slack message."""
    parts = [f"{s['certificates']} certificate{'s' if s['certificates'] != 1 else ''} checked"]
    parts.append(f"{s['deficient']} deficient" if s["deficient"] else "none deficient")
    if s["warnings"]:
        parts.append(f"{s['warnings']} with warnings")
    if s["renewals"]:
        expired = sum(r["days_left"] < 0 for r in s["renewals"])
        parts.append(f"{len(s['renewals'])} renewal{'s' if len(s['renewals']) != 1 else ''} due"
                     + (f" ({expired} already expired)" if expired else ""))
    return f"{s['project']}: " + ", ".join(parts) + "."


def _md(text: str) -> str:
    """Escape for a Markdown table cell (no HTML entities, so apostrophes stay readable)."""
    return text.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def markdown(s: dict) -> str:
    icon = {"COMPLIANT": "✅", "COMPLIANT_WITH_WARNINGS": "⚠️", "DEFICIENT": "❌"}
    out = [f"# COI report — {s['project']}", "", f"_Generated by coi-lint on {s['date']}._", "",
           headline(s), "", "## Certificates", "", "| Insured | Verdict | Fail | Warn | Waived | Problems |",
           "|---|---|---|---|---|---|"]
    for i in s["insureds"]:
        probs = "<br>".join(_md(p) for p in i["problems"]) or "—"
        out.append(f"| {_md(i['insured'])} | {icon[i['verdict']]} {i['verdict'].replace('_', ' ').lower()} "
                   f"| {i['fail']} | {i['warn']} | {i['waived']} | {probs} |")
    if s["top_failures"]:
        out += ["", "## Most common problems", ""]
        out += [f"- **{t['rule']}** {t['title']}: {t['count']}× (run `coi-lint explain {t['rule']}`)"
                for t in s["top_failures"]]
    if s["renewals"]:
        out += ["", "## Renewals due", "", "| Expires | Insured | Coverage | Policy | Days left |", "|---|---|---|---|---|"]
        out += [f"| {r['expires']} | {_md(r['insured'])} | {r['coverage']} | {r['policy_number']} | "
                f"{r['days_left'] if r['days_left'] >= 0 else 'expired'} |" for r in s["renewals"]]
    return "\n".join(out) + "\n"


def to_csv(s: dict) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["insured", "producer", "verdict", "fail", "warn", "waived", "pass", "problems", "source"])
    for i in s["insureds"]:
        w.writerow([i["insured"], i["producer"], i["verdict"], i["fail"], i["warn"], i["waived"], i["pass"],
                    " | ".join(i["problems"]), i["source"]])
    return buf.getvalue()


def to_json(s: dict) -> str:
    return json.dumps(s, indent=2)


